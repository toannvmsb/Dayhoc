/**
 * Regenerates docs/implementation/B3_DEMO_OUTPUT.md from the B3 functional demo
 * (doc 17 §7). Run: `node packages/testing/scripts/b3-demo-report.mjs`
 * (build @copilot/testing first).
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { runB3Demo } from '../dist/demo/b3-context-demo.js';

const here = dirname(fileURLToPath(import.meta.url));
const outPath = resolve(here, '../../../docs/implementation/B3_DEMO_OUTPUT.md');

const arr = (xs) => `[${xs.join(', ')}]`;
const lines = [
  '# B3 Functional Demo — Curriculum Clock + Learning Context Resolver',
  '',
  '_Generated by `packages/testing/scripts/b3-demo-report.mjs` from `runB3Demo()`.',
  'Deterministic over its inputs — re-run after any resolver/clock change._',
  '',
];

for (const d of runB3Demo()) {
  const e = d.expected;
  const r = d.resolved;
  const h = d.paceDeltaHypothesis;
  lines.push(`### ${d.label}`);
  lines.push(
    `  Expected (ước tính) : lesson ${e.lessonId} · window ${arr(e.window.lessonIds)} · ${e.confidence} ` +
      `· calendar ${e.calendar.calendarId} (rev ${e.calendar.version}, ${e.calendar.status})`,
  );
  lines.push(
    `  Resolved            : lesson ${r.lessonId} · source ${r.source} · ${r.confidence} ` +
      `· window ${arr(r.window)} · guardrail ${r.guardrailApplied ?? 'none'}` +
      (r.lastVerifiedAt ? ` · lastVerifiedAt ${r.lastVerifiedAt}` : ''),
  );
  lines.push(
    `  paceDelta applied   : ${d.paceDelta}` +
      (d.paceDelta !== 0 ? ' (LOW-confidence auto — shifts FUTURE estimate only, not verified context)' : ''),
  );
  lines.push(
    `  pace hypothesis     : ${h.value} over ${h.spanWeeks} school week(s), n=${h.observationCount} — ${h.rationale}`,
  );
  lines.push(`  conflicts           : ${JSON.stringify(d.conflicts)}`);
  lines.push('');
}

writeFileSync(outPath, lines.join('\n'));
console.info(`wrote ${outPath}`);
